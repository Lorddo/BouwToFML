/** @typedef {{ en: string, nl: string, th: string }} Tri */

/** @param {Record<string, any>} node */
function splitLocales(node) {
  const en = {}
  const nl = {}
  const th = {}
  for (const [key, value] of Object.entries(node)) {
    if (value && typeof value === 'object' && 'en' in value && 'nl' in value && 'th' in value) {
      en[key] = value.en
      nl[key] = value.nl
      th[key] = value.th
    } else if (value && typeof value === 'object') {
      const child = splitLocales(value)
      en[key] = child.en
      nl[key] = child.nl
      th[key] = child.th
    }
  }
  return { en, nl, th }
}

